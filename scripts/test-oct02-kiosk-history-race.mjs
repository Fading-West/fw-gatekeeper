import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root = process.env.GK_CHECKOUT || process.cwd();
const source = fs.readFileSync(path.join(root, 'pi-kiosk/templates/index.html'), 'utf8');
const extract = (start, end) => source.slice(source.indexOf(start), source.indexOf(end, source.indexOf(start)));
const functions = extract('function setAdminVisible(', 'function openSupervisorDialog(') + extract('async function fetchLog(', 'async function submitManualClock(');
let calls = 0;
let resolveFetch;
const element = () => ({ classList: { toggle() {} }, textContent: '' });
const logList = { innerHTML: '', replaceChildren() { this.innerHTML = ''; } };
const context = vm.createContext({ logList, adminControls: element(), adminPanel: element(), supervisorUnlock: element(), document: { body: element() },
  KioskRendering: { attendance: data => JSON.stringify(data) },
  fetch: () => { calls++; return new Promise(resolve => { resolveFetch = resolve; }); } });
vm.runInContext(`let adminVisible = false; let supervisorStateVersion = 0; ${functions}; globalThis.testApi={setAdminVisible,fetchLog};`, context);
const api = context.testApi;
await api.fetchLog();
assert.equal(calls, 0, 'locked page must not request history');
api.setAdminVisible(true);
let request = api.fetchLog();
resolveFetch({ ok: true, json: async () => [{ worker_name: 'Synthetic Employee' }] });
await request;
assert.match(logList.innerHTML, /Synthetic Employee/);
api.setAdminVisible(false);
assert.equal(logList.innerHTML, '', 'relock clears already displayed history');
api.setAdminVisible(true);
request = api.fetchLog();
api.setAdminVisible(false);
api.setAdminVisible(true);
resolveFetch({ ok: true, json: async () => [{ worker_name: 'Stale Synthetic Employee' }] });
await request;
assert.equal(logList.innerHTML, '', 'old-session response cannot repaint after lock/unlock');
request = api.fetchLog();
api.setAdminVisible(false);
resolveFetch({ ok: false });
await request;
assert.equal(logList.innerHTML, '', 'late failure cannot repaint while locked');
console.log('PASS: locked fetch suppression, history clearing, late-success and late-failure relock races');
